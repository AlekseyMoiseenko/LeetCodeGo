package hash

import (
	"testing"

	"github.com/stretchr/testify/require"
)

// Constraints:
// n == nums.length
// 1 <= n <= 5 * 10^4
// -10^9 <= nums[i] <= 10^9
// The input is generated such that a majority element will exist in the array.
func TestMajorityElement(t *testing.T) {
	testCases := []struct {
		nums     []int
		expected int
	}{
		{
			nums:     []int{1, 1, 1},
			expected: 1,
		},
		{
			nums:     []int{3, 2, 3},
			expected: 3,
		},
		{
			nums:     []int{2, 2, 1, 1, 1, 2, 2},
			expected: 2,
		},
		{
			nums:     []int{42, -564520472, 42, 42, -188553833, -742638669, -742638669, 42, 252371522, -742638669, 314538302, 42, -742638669, 42, 42, -564520472, 42, 42, 42, -188553833, 42, -742638669, -742638669, -564520472, -742638669, 42, 42, 42, 42, -188553833, 42, -742638669, 252371522, -742638669, 42, -742638669, 42, -564520472, -742638669, 42, 42, 42, -564520472, -188553833, 42, 42, 42, 42, -742638669, 42, 42, -742638669, -742638669, 42, -742638669, 42, 42, -742638669, 42, -188553833, -188553833, 42, 42, -188553833, 314538302, -742638669, 42, 42, -564520472, 42, -188553833, -188553833, -742638669, 42, 42, 42, -564520472, -188553833, 42, 871042302, 42, 42, 42, -188553833, -564520472, 42, 42, 871042302, -742638669, -742638669, 314538302, 42, 42, -742638669, 314538302, 42, 42, 42, 42, -564520472, -564520472},
			expected: 42,
		},
	}

	for _, tc := range testCases {
		require.Equal(t, tc.expected, majorityElement(tc.nums))
	}
}
